const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const elements = new Map();
function el(id){if(!elements.has(id))elements.set(id,{value:'',innerHTML:'',hidden:false,disabled:false,addEventListener(){},classList:{toggle(){}},setAttribute(){},removeAttribute(){}});return elements.get(id)}
const document={querySelector:el,querySelectorAll(){return []},getElementById:el};
const context={document,window:{addEventListener(){}},location:{hash:''},fetch:()=>new Promise(()=>{}),URLSearchParams,console};
vm.createContext(context);
vm.runInContext(fs.readFileSync('static/app.js','utf8'),context);
vm.runInContext(`run={id:'test',metrics:[{modelo:'m:latest',tipo:'decision',precision:75,mediana:0.03,tiempos_incluidos:4,total_segundos:0.12,aciertos:3,errores:1,invalidas:1,fallos:1,intentadas:6,previstas:8}]};renderDashboard(run);`,context);
assert.match(el('#dashboard-accuracy').innerHTML,/75%/);
assert.match(el('#dashboard-time').innerHTML,/0.03 s/);
assert.match(el('#dashboard-table').innerHTML,/1 \/ 1/);
assert.match(el('#dashboard-distribution').innerHTML,/Fallos técnicos/);
assert.match(el('#dashboard-distribution').innerHTML,/Previstas: 8/);
vm.runInContext(`run={id:'empty',metrics:[]};renderDashboard(run);`,context);
assert.match(el('#dashboard-table').innerHTML,/Sin resultados/);
console.log('Dashboard: presentacion de datos y estado vacio verificados.');
assert.strictEqual(vm.runInContext('modelSize(3700000000)',context),'3,7 GB');
assert.strictEqual(vm.runInContext('modelSize(322000000)',context),'322 MB');
